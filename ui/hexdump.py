import os

# Run from ui/ (npm run dump). Writes every file of the build into one header for the firmware to
# serve: include/ui/WebAssets.h, a WebAsset table (see include/web/WebUi.h). Files the build
# gzipped (name.gz) are served with Content-Encoding: gzip under their original name.
SRC = "dist"
DEST = os.path.join("..", "include", "ui")

CONTENT_TYPES = {
    ".html": "text/html",
    ".js": "text/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".webmanifest": "application/manifest+json",
}

os.makedirs(DEST, exist_ok=True)
for file in os.listdir(DEST):
    os.remove(os.path.join(DEST, file))

assets = []
for file in sorted(os.listdir(SRC)):
    path = os.path.join(SRC, file)
    if not os.path.isfile(path):
        continue
    gzipped = file.endswith(".gz")
    name = file[:-3] if gzipped else file
    extension = os.path.splitext(name)[1]
    if extension not in CONTENT_TYPES:
        raise SystemExit(f"hexdump.py: no content type for {name}, add one to CONTENT_TYPES")
    with open(path, "rb") as f:
        data = f.read()
    url = "/" if name == "index.html" else f"/{name}"
    assets.append((url, CONTENT_TYPES[extension], data, gzipped))

with open(os.path.join(DEST, "WebAssets.h"), "w") as header:
    header.write("#pragma once\n\n// Generated by ui/hexdump.py from the web UI build, don't edit\n\n")
    header.write("#include \"web/WebUi.h\"\n\n")
    for index, (url, _, data, _) in enumerate(assets):
        header.write(f"// {url}\nstatic const uint8_t webAsset{index}[] = {{\n")
        for i in range(0, len(data), 16):
            header.write("    " + ", ".join(f"0x{byte:02x}" for byte in data[i:i + 16]) + ",\n")
        header.write("};\n\n")
    header.write("static const WebAsset WebAssets[] = {\n")
    for index, (url, content_type, data, gzipped) in enumerate(assets):
        header.write(f"    {{\"{url}\", \"{content_type}\", webAsset{index}, {len(data)}, {'true' if gzipped else 'false'}}},\n")
    header.write("};\n")

print(f"Wrote {len(assets)} web assets to {DEST}")
