import os
import subprocess
from datetime import datetime

Import("env")

# Writes include/FirmwareVersion.h with the version reported by the board, so an update can be
# checked to have taken. Tagged release builds show the tag ("v1.2.0"), others the commit
# ("v1.2.0-3-ga25165f", or "a25165f" before the first tag). Builds with uncommitted changes add
# the build time, since they'd all look the same otherwise.

def describe():
    try:
        return subprocess.check_output(["git", "describe", "--tags", "--always", "--dirty"],
                                       cwd=env.subst("$PROJECT_DIR"), text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"

version = describe()
if version.endswith("-dirty"):
    version = version[:-len("-dirty")] + "+" + datetime.now().strftime("%Y%m%d-%H%M")

header_path = os.path.join(env.subst("$PROJECT_INCLUDE_DIR"), "FirmwareVersion.h")
header = (
    "#pragma once\n\n"
    "// Generated by version.py at build time, don't edit\n"
    f"#define FIRMWARE_VERSION \"{version}\"\n"
)

# Only rewritten when it changes, so unchanged builds don't recompile what includes it
current = None
if os.path.exists(header_path):
    with open(header_path, "r") as f:
        current = f.read()
if current != header:
    with open(header_path, "w") as f:
        f.write(header)

print(f"Firmware version {version}")
